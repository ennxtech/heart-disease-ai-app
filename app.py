FEATURES = ["age", "sex", "cp", "trestbps", "chol", "fbs", "restecg", "thalach", "exang", "oldpeak", "slope", "ca", "thal"]

@st.cache_resource
def load_model():
    return joblib.load(Path(__file__).parent / "heart_disease_model.joblib")

